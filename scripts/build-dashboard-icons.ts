type IconNode = [tag: string, attrs: Record<string, string | number>];

const require = createRequire(import.meta.url);
const kebab = (k: string) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const SAFE_TAG = /^[a-z]+$/;
const SAFE_ATTR = /^[a-zA-Z-]+$/;
const SAFE_VALUE = /^[^"<>&]*$/;

/** The SVG inner markup of one icon. Only plain tags, attribute names and quote-free values: anything else throws. */
export function iconMarkup(name: string): string {
  // The package's export map turns `<name>Icon` into dist/cjs/<name>Icon.js; each file holds one icon.
  const nodes = require(`@hugeicons/core-free-icons/${name}Icon`) as IconNode[];
  return nodes
    .map(([tag, attrs]) => {
      if (!SAFE_TAG.test(tag)) throw new Error(`unexpected tag in ${name}`);
      const parts = Object.entries(attrs)
        .filter(([a]) => a !== 'key')
        .map(([a, v]) => {
          const value = String(v);
          if (!SAFE_ATTR.test(a) || !SAFE_VALUE.test(value)) throw new Error(`unexpected attribute in ${name}`);
          return `${kebab(a)}="${value}"`;
        });
      return `<${tag} ${parts.join(' ')}/>`;
    })
    .join('');
}

/** The whole generated file. */
export function iconsModule(): string {
  const icons = Object.fromEntries(Object.entries(ICON_PICK).map(([key, name]) => [key, iconMarkup(name)]));
  return (
    '// Generated by scripts/build-dashboard-icons.ts from @hugeicons/core-free-icons (MIT). Do not edit by hand.\n' +
    `export const HI = ${JSON.stringify(icons, null, 1)};\n`
  );
}

export const ICONS_FILE = fileURLToPath(new URL('../src/web/public/icons.js', import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(ICONS_FILE, iconsModule());
  console.log(`wrote ${Object.keys(ICON_PICK).length} icons`);
}
